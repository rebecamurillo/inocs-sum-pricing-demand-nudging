import json

def parse_bilevel_instance1(json_file_path):
    """
    Reads the JSON instance file (generated by your instance creation code)
    and returns a dictionary of organized data structures for your optimization.
    """
    with open(json_file_path, "r") as f:
        data = json.load(f)
    
    # ----------------------------------------------------------------
    # 1. Basic top-level information
    # ----------------------------------------------------------------
    random_seed      = data["random_seed"]         # e.g., 42
    max_disp_alts    = data["max_disp_alts"]       # L in your model
    ridership_weight = data["ridership_weight"]    # φ (varphi) in your objective
    nodes            = data["nodes"]               # list of node IDs
    edges            = data["edges"]               # list of edges (pairs/tuples)
    
    fixed_pt_price_value = data["fixed_pt_price_value"]  # fixed PT fare
    bike_cost_operator   = data["bike_cost_operator"]    # \bar{P} (bike cost per minute)

    # ----------------------------------------------------------------
    # 2. Bike stations & capacity/inventory
    # ----------------------------------------------------------------
    bike_stations_data = data["bike_stations"]  # a dict with { station_list, station_capacity, station_inventory }
    stations_list      = bike_stations_data["station_list"]         # list of station node IDs
    station_capacity   = bike_stations_data["station_capacity"]     # dict {station_id: capacity}
    station_inventory  = bike_stations_data["station_inventory"]    # dict {station_id: inventory}

    # ----------------------------------------------------------------
    # 3. OD pairs: parse demand, alpha, beta, theta
    # ----------------------------------------------------------------
    # data["OD_pairs"] is a list of dicts: 
    #   [ 
    #     { "origin": ..., "destination": ..., "demand": ..., "alpha": ..., "beta": ..., "theta": ... },
    #     ...
    #   ]
    OD_pairs_list = data["OD_pairs"]
    OD_pairs   = []           # we can store (o, d) tuples here
    demands    = {}           # (o, d) -> demand
    alpha_vals = {}           # (o, d) -> alpha
    beta_vals  = {}           # (o, d) -> beta
    theta_vals = {}           # (o, d) -> theta (if relevant in your model)

    for od_info in OD_pairs_list:
        o = od_info["origin"]
        d = od_info["destination"]
        OD_pairs.append((o, d))
        
        demands[(o, d)]    = od_info["demand"]
        alpha_vals[(o, d)] = od_info["alpha"]
        beta_vals[(o, d)]  = od_info["beta"]
        theta_vals[(o, d)] = od_info["theta"]  # stored if needed

    # ----------------------------------------------------------------
    # 4. Arcs: PT+Bike (A1), PT-only (A2), and Car paths (B)
    # ----------------------------------------------------------------
    # Each is a dict keyed by the string f"{o}_{d}", each mapping to a list of arcs.
    arcs_pt_bike = data["arcs_pt_bike"]   # e.g. {"0_3": [ {...}, {...}], "1_4": [ {...} ], ...}
    arcs_pt_only = data["arcs_pt_only"]   # similar
    car_paths    = data["car_paths"]      # similar

    # Create dictionaries to store arc parameters
    pt_time      = {}
    bike_time    = {}
    fixed_pt     = {}
    bike_cost    = {}
    transfers    = {}
    travel_time  = {}
    fuel_cost    = {}
    mile_type    = {}
    # For each (o, d) in OD_pairs, process the arcs
    for (o, d) in OD_pairs:
        od_key = f"{o}_{d}"

        # PT+Bike arcs
        for arc in arcs_pt_bike.get(od_key, []):
            arc_id = arc["arc_id"]
            pt_time[(o, d, arc_id)]        = arc.get("pt_time", 0.0)
            bike_time[(o, d, arc_id)]      = arc.get("bike_time", 0.0)
            fixed_pt[(o, d, arc_id)]       = arc.get("fixed_pt_price", 0.0)
            bike_cost[(o, d, arc_id)]      = arc.get("bike_cost", 0.0)
            transfers[(o, d, arc_id)]      = arc.get("transfers", 0)
            mile_type                      = arc["mile_type"]
            # For car-based attributes, set 0
            travel_time[(o, d, arc_id)]    = 0.0
            fuel_cost[(o, d, arc_id)]      = 0.0

        # PT-Only arcs
        for arc in arcs_pt_only.get(od_key, []):
            arc_id = arc["arc_id"]
            pt_time[(o, d, arc_id)]        = arc.get("pt_time", 0.0)
            bike_time[(o, d, arc_id)]      = 0.0  # no biking for PT-only
            fixed_pt[(o, d, arc_id)]       = arc.get("fixed_pt_price", 0.0)
            bike_cost[(o, d, arc_id)]      = 0.0
            transfers[(o, d, arc_id)]      = arc.get("transfers", 0)
            # Car-based attributes are 0
            travel_time[(o, d, arc_id)]    = 0.0
            fuel_cost[(o, d, arc_id)]      = 0.0

        # Car arcs
        for arc in car_paths.get(od_key, []):
            arc_id = arc["arc_id"]
            # Car arcs may not have PT or bike usage, so set those to 0:
            pt_time[(o, d, arc_id)]        = 0.0
            bike_time[(o, d, arc_id)]      = 0.0
            fixed_pt[(o, d, arc_id)]       = 0.0
            bike_cost[(o, d, arc_id)]      = 0.0
            transfers[(o, d, arc_id)]      = 0
            # Store the car-specific attributes
            travel_time[(o, d, arc_id)]    = arc.get("travel_time", 0.0)
            fuel_cost[(o, d, arc_id)]      = arc.get("fuel_cost", 0.0)

    # ----------------------------------------------------------------
    # 5. Delta_{i,a} for capacity constraints
    # ----------------------------------------------------------------
    delta_ia = data["delta_ia"]

    # ----------------------------------------------------------------
    # 6. Build a final dictionary to return
    # ----------------------------------------------------------------
    parsed_data = {
        # Basic info
        "random_seed": random_seed,
        "max_disp_alts": max_disp_alts,
        "ridership_weight": ridership_weight,
        "nodes": nodes,
        "edges": edges,
        
        # Operator cost parameters
        "fixed_pt_price_value": fixed_pt_price_value,   #global
        "bike_cost_operator": bike_cost_operator,       #global
        "fixed_pt_price": fixed_pt,                     #for each arc
        "bike_cost": bike_cost,                         #for each arc
        
        # Bike stations & capacity
        "stations_list": stations_list,
        "station_capacity": station_capacity,
        "station_inventory": station_inventory,

        # OD pairs & parameters
        "OD_pairs": OD_pairs,
        "demands": demands,
        "alpha_vals": alpha_vals,
        "beta_vals": beta_vals,
        "theta_vals": theta_vals,

        # Arc sets (raw)
        "arcs_pt_bike": arcs_pt_bike,
        "arcs_pt_only": arcs_pt_only,
        "car_paths": car_paths,
        
        # Additional dictionaries for direct use in model
        "pt_time": pt_time,
        "bike_time": bike_time,

        "transfers": transfers,
        "travel_time": travel_time,
        "fuel_cost": fuel_cost,

        # Delta
        "delta_ia": delta_ia
    }


    return parsed_data
